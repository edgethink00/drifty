// @vitest-environment jsdom
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

const css = readFileSync("src/features/pet-mode/petMode.css", "utf8");
const app = readFileSync("src/features/pet-mode/PetModeWindowApp.tsx", "utf8");
const cat = readFileSync("src/features/pet-mode/PetModeCat.tsx", "utf8");
const native = readFileSync("../../src-tauri/src/commands/pet_hit_region.rs", "utf8");
const capability = JSON.parse(readFileSync("../../src-tauri/capabilities/pet-mode-window.json", "utf8")) as {
  readonly permissions: readonly string[];
};
const registration = readFileSync("../../src-tauri/src/lib.rs", "utf8");
const artifact = JSON.parse(readFileSync("public/pet-mode/hit-regions-v1.json", "utf8")) as {
  readonly version: number;
  readonly regions: Readonly<Record<string, readonly number[]>>;
};

describe("pet mode hit target", () => {
  it("uses a versioned pose/frame artifact instead of one hand-maintained idle polygon", () => {
    expect(artifact.version).toBe(1);
    expect(Object.keys(artifact.regions)).toHaveLength(127);
    for (const region of ["idle", "happy", "sit", "sleep", "drag", "release", "gait:29", "paw:16", "stretch:36", "tail:36"]) {
      expect(artifact.regions[region]?.length, `${region} region`).toBeGreaterThan(0);
    }
    expect(css).not.toContain("clip-path: polygon(");
  });

  it("publishes a fail-closed native region for the committed rendered frame", () => {
    expect(cat).toContain("useLayoutEffect");
    expect(cat).toContain("publishPetModeHitRegion");
    /* Every term here is a reason the WebView must not own the pointer. The
       menu term joined them because AppKit holds the pointer for the lifetime
       of an open popup, and republishing the silhouette underneath it can hand
       input back mid-menu. */
    expect(app).toMatch(/hitRegionInteractive=\{petModeEnabled\s*&& petVisible\s*&& phase !== "entry"\s*(?:\/\*[\s\S]*?\*\/\s*)?&& !menuHolding\s*&& hitRegionTransitionCount === 0\}/);
    expect(native).toContain("setIgnoresMouseEvents(!interactive)");
    expect(native).toContain("state.spans.is_empty()");
  });

  it("keeps the WebView button aligned with native ownership", () => {
    expect(css).toContain(".pet-mode-hit-target { pointer-events: auto; }");
    expect(app).not.toContain("pet-mode-hit-shape");
  });

  it("samples nearby cursor gaze without expanding the native hit region", () => {
    expect(app).toContain("sampleNativePetCursor");
    expect(app).toContain("gazeOffset={gazeOffset}");
    expect(cat).toContain("pet-mode-cat__vector-eyes--gaze");
    expect(css).toContain(".pet-mode-cat__vector-eyes--gaze");
    expect(registration).toContain("pet_mode_cursor_sample");
    expect(capability.permissions).toContain("allow-pet-mode-cursor-sample");
    expect(native).toContain("setIgnoresMouseEvents(!interactive)");
  });

  it("registers and authorizes the new least-privilege native command", () => {
    expect(registration).toContain("pet_mode_update_hit_region");
    expect(capability.permissions).toContain("allow-pet-mode-update-hit-region");
    const permission = readFileSync(
      "../../src-tauri/permissions/autogenerated/pet_mode_update_hit_region.toml",
      "utf8",
    );
    expect(permission).toContain('commands.allow = ["pet_mode_update_hit_region"]');
  });
});
