function rampBetween(inkHex: string, furHex: string): readonly string[] {
  return [1,3,5].map(offset => {
    const ink = parseInt(inkHex.slice(offset,offset+2),16)/255;
    const fur = parseInt(furHex.slice(offset,offset+2),16)/255;
    return Array.from({length:18},(_,n) => (ink+(fur-ink)*Math.min(1,Math.max(0,(n-2)/13))+1e-6).toFixed(8)).join(" ");
  });
}

export function petModeCoatRamp(coat: PetModeCoat): readonly string[] {
  const spec = getPetModeCoatSpec(coat);
  return rampBetween(spec.pattern?.furInk ?? spec.ink, spec.fur);
}

/** Ramps of a pattern skin's mid and dark layers: same ink (the face colour), each to its own fur tone. */
export function petModePatternRamps(coat: PetModeCoat): { readonly mid: readonly string[]; readonly dark: readonly string[] } | null {
  const spec = getPetModeCoatSpec(coat);
  return spec.pattern ? { mid: rampBetween(spec.ink, spec.pattern.mid), dark: rampBetween(spec.ink, spec.pattern.dark) } : null;
}
