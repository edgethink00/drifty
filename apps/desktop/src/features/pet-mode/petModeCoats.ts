/**
 * A pattern skin paints darker points over the fur. Every frame is recolored
 * three times - fur, a warm mid tone and the dark point colour - and the two
 * upper copies are masked per frame with masks generated by
 * scripts/pet-mode-siamese/generate-masks.mjs. Stacking the mid tone under the
 * dark one follows the reviewed colour curve, so the fade never turns grey.
 */
export type PetModeCoatPattern = {
  readonly kind: "siamese";
  readonly mid: string;
  readonly dark: string;
  /** Ink of the fur layer. The face always sits under the dark point, so this only shows if a mask is missing. */
  readonly furInk: string;
};
