/** Chat speaks every display language of the app. */
export type ChatLanguage = DisplayLanguage;

export function chatLanguage(language: string): ChatLanguage {
  return isDisplayLanguage(language) ? language : "en";
}

/** The formatting locale of a chat language, from the app's language catalog. */
export function chatLocale(language: ChatLanguage): string {
  return DISPLAY_LANGUAGES.find((entry) => entry.value === language)?.locale ?? "en-US";
}

/** A month-and-day date in the given locale, such as Oct 26 or 10월 26일. */
export function chatShortDate(iso: string, locale: string): string {
  return new Date(iso).toLocaleDateString(locale, { month: "short", day: "numeric" });
}

