const shortDate = (iso: string, locale: string) => new Date(iso).toLocaleDateString(locale, { month: "short", day: "numeric" });
const seconds = (value: number, unit: string, minuteUnit: string) =>
  value < 60 ? value + unit : Math.floor(value / 60) + minuteUnit + (value % 60 ? " " + (value % 60) + unit : "");

