import { existsSync, readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

import { developerToolsInvokeCommands } from "./developerToolsClient";

const rustLibSource = readFileSync(
  new URL("../../../../../src-tauri/src/lib.rs", import.meta.url),
  "utf8",
);
const mainWindowCapability = JSON.parse(
  readFileSync(
    new URL("../../../../../src-tauri/capabilities/main-window.json", import.meta.url),
    "utf8",
  ),
) as { permissions: string[] };

function allowPermission(command: string): string {
  return `allow-${command.replace(/_/g, "-")}`;
}

describe("developer tools native command contract", () => {
  for (const command of Object.values(developerToolsInvokeCommands)) {
    it(`registers and authorizes ${command}`, () => {
      expect(rustLibSource).toMatch(new RegExp(`\\b${command}\\b`));
      expect(mainWindowCapability.permissions).toContain(allowPermission(command));
      expect(
        existsSync(
          new URL(
            `../../../../../src-tauri/permissions/autogenerated/${command}.toml`,
            import.meta.url,
          ),
        ),
      ).toBe(true);
    });
  }
});
