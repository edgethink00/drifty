import { existsSync, readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

import { feedbackDiagnosticsInvokeCommands, parseNativeFeedbackDiagnostics } from "./feedbackDiagnosticsClient";

const rustLibSource = readFileSync(new URL("../../../../../src-tauri/src/lib.rs", import.meta.url), "utf8");
const buildSource = readFileSync(new URL("../../../../../src-tauri/build.rs", import.meta.url), "utf8");
const mainWindowCapability = JSON.parse(
  readFileSync(new URL("../../../../../src-tauri/capabilities/main-window.json", import.meta.url), "utf8"),
) as { permissions: string[] };

describe("feedback diagnostics native command", () => {
  for (const command of Object.values(feedbackDiagnosticsInvokeCommands)) {
    it(`registers and authorizes ${command} for the main window only`, () => {
      expect(rustLibSource).toMatch(new RegExp(`\\b${command}\\b`));
      expect(buildSource).toContain(`"${command}"`);
      expect(mainWindowCapability.permissions).toContain(`allow-${command.replace(/_/g, "-")}`);
      expect(existsSync(new URL(`../../../../../src-tauri/permissions/autogenerated/${command}.toml`, import.meta.url))).toBe(true);
    });
  }

  it("reads the native payload and skips malformed crash entries", () => {
    expect(parseNativeFeedbackDiagnostics({
      osName: "macos",
      osVersion: "Version 26.1 (Build 25B78)",
      arch: "aarch64",
      lastWindowingError: null,
      recentCrashes: [
        { incidentId: "A", kind: "EXC_BAD_ACCESS (SIGSEGV)", appVersion: "1.12.5", occurredAtMs: 1 },
        { incidentId: "B", kind: 3 },
      ],
    })).toEqual({
      osName: "macos",
      osVersion: "Version 26.1 (Build 25B78)",
      arch: "aarch64",
      lastWindowingError: null,
      recentCrashes: [{ incidentId: "A", kind: "EXC_BAD_ACCESS (SIGSEGV)", appVersion: "1.12.5", occurredAtMs: 1 }],
    });
    expect(parseNativeFeedbackDiagnostics(null)).toBeNull();
    expect(parseNativeFeedbackDiagnostics({ osName: "macos" })).toBeNull();
  });
});
