const bool: Rule = v => typeof v === "boolean" ? v : null;
const num: Rule = v => typeof v === "number" && Number.isFinite(v) && v >= 0 && v <= Number.MAX_SAFE_INTEGER ? v : null;
const signed: Rule = v => typeof v === "number" && Number.isSafeInteger(v) && Math.abs(v) <= 86_400_000 ? v : null;
